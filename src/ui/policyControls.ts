/** Add explicit control names and descriptions to policy rows generated by the
 * dashboard. Call after setting innerHTML and before wiring change handlers. */
export function annotatePolicyControls(host: HTMLElement): void {
  host.classList.add("policy-controls-enhanced");
  for (const row of host.querySelectorAll<HTMLElement>(".policy-row")) {
    const hasHeader = [...row.children].some((child) => child.tagName === "B");
    if (hasHeader) {
      row.classList.add("policy-header");
      continue;
    }
    row.classList.add("policy-fields");
    const category = row.querySelector<HTMLElement>(":scope > strong")?.textContent?.trim() || "Incident policy";
    const controls = row.querySelectorAll<HTMLInputElement | HTMLSelectElement>("select[data-policy], input[data-policy], select[data-item-policy], input[data-item-policy]");
    for (const control of controls) {
      if (control.parentElement?.classList.contains("policy-field")) continue;
      const key = (control.dataset.policy ?? control.dataset.itemPolicy ?? "").split(":")[1] ?? "";
      const description = POLICY_FIELDS[key];
      if (!description) continue;
      const field = document.createElement("label");
      field.className = `policy-field${control instanceof HTMLInputElement && control.type === "checkbox" ? " is-toggle" : ""}`;
      const visibleLabel = document.createElement("span");
      visibleLabel.className = "policy-field-label";
      visibleLabel.textContent = description.label;
      field.appendChild(visibleLabel);
      field.appendChild(control);
      row.appendChild(field);
      const accessibleName = `${category}: ${description.label}`;
      control.setAttribute("aria-label", accessibleName);
      control.title = `${accessibleName}. ${description.explanation}`;
      field.title = description.explanation;
    }
  }
}
